from __future__ import annotations
import argparse
import sqlite3
import sys
from pathlib import Path
from typing import List, Dict, Any


def sanitize_cs_identifier(name: str) -> str:
    """Escapes C# keywords and invalid characters for C# identifiers."""
    cs_keywords = {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
        "checked", "class", "const", "continue", "decimal", "default", "delegate",
        "do", "double", "else", "enum", "event", "explicit", "extern", "false",
        "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit",
        "in", "int", "interface", "internal", "is", "lock", "long", "namespace",
        "new", "null", "object", "operator", "out", "override", "params", "private",
        "protected", "public", "readonly", "ref", "return", "sbyte", "sealed",
        "short", "sizeof", "stackalloc", "static", "string", "struct", "switch",
        "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked",
        "unsafe", "ushort", "using", "virtual", "void", "volatile", "while"
    }
    cleaned = "".join(c if c.isalnum() or c == '_' else '_' for c in name)
    if not cleaned or cleaned[0].isdigit():
        cleaned = f"_{cleaned}"
    if cleaned in cs_keywords:
        return f"@{cleaned}"
    return cleaned


def map_type_to_csharp(type_expr: str | None, is_param: bool = False) -> str:
    """Maps language-agnostic or native type expressions to canonical C# types."""
    if not type_expr or type_expr.strip() in ("", "None", "void", "()"):
        return "object?" if is_param else "void"
    t = type_expr.strip()
    mapping = {
        "int": "int",
        "float": "double",
        "str": "string",
        "string": "string",
        "bool": "bool",
        "bytes": "byte[]",
        "list": "System.Collections.Generic.List<object>",
        "dict": "System.Collections.Generic.Dictionary<string, object>",
        "Any": "object",
        "object": "object",
        "i32": "int",
        "i64": "long",
        "u32": "uint",
        "u64": "ulong",
        "f32": "float",
        "f64": "double",
        "usize": "nuint",
        "isize": "nint",
    }
    return mapping.get(t, "object")


class CSharpBindgen:
    def __init__(self, db_path: Path):
        self.db_path = db_path
        if not self.db_path.exists():
            raise FileNotFoundError(f"Database catalog not found: {self.db_path}")

    def generate(self, target_namespace: str = "Utss.Generated") -> str:
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        cur = conn.cursor()

        # Query top-level containers (classes/modules)
        cur.execute(
            """
            SELECT c.container_id, c.short_name, c.container_kind, c.docstring
            FROM containers c
            WHERE c.container_kind IN ('class', 'struct', 'module', 'package', 'namespace')
            ORDER BY c.container_id ASC
            LIMIT 100
            """
        )
        containers = cur.fetchall()

        lines: List[str] = [
            "// <auto-generated>",
            "//     This code was generated by UTSS C# Bindgen (utss_csharp_bindgen.py).",
            "//     Runtime: Universal Type & Symbol System (UTSS)",
            "//     Source Database: " + self.db_path.name,
            "//",
            "//     Under the UTSS Generated Output Exception, you own 100% of this generated",
            "//     code and may license it under any terms without restriction.",
            "// </auto-generated>",
            "#nullable enable",
            "",
            "using System;",
            "using System.Threading.Tasks;",
            "using System.Collections.Generic;",
            "",
            f"namespace {target_namespace}",
            "{",
        ]

        for cont in containers:
            c_name = sanitize_cs_identifier(cont["short_name"])
            c_kind = "class" if cont["container_kind"] in ("class", "module", "package", "namespace") else "struct"
            doc = cont["docstring"] or f"UTSS harvested container: {cont['short_name']}"

            lines.append("    /// <summary>")
            for doc_line in doc.splitlines()[:3]:
                lines.append(f"    /// {doc_line.strip()}")
            lines.append("    /// </summary>")
            lines.append(f"    public partial {c_kind} {c_name}")
            lines.append("    {")

            # Fetch methods and callables
            cur.execute(
                """
                SELECT s.symbol_id, s.name, s.symbol_kind, c.return_type_expr, c.is_static, c.is_async
                FROM symbols s
                JOIN callables c ON s.symbol_id = c.symbol_id
                WHERE s.container_id = ?
                LIMIT 50
                """,
                (cont["container_id"],)
            )
            methods = cur.fetchall()

            for m in methods:
                m_name = sanitize_cs_identifier(m["name"])
                ret_type = map_type_to_csharp(m["return_type_expr"])
                if m["is_async"]:
                    ret_type = f"Task<{ret_type}>" if ret_type != "void" else "Task"
                static_mod = "static " if m["is_static"] else ""

                # Fetch parameters
                cur.execute(
                    """
                    SELECT name, type_expr, default_expr, ordinal
                    FROM parameters
                    WHERE callable_symbol_id = ?
                    ORDER BY ordinal ASC
                    """,
                    (m["symbol_id"],)
                )
                params = cur.fetchall()
                param_strs = []
                for p in params:
                    p_name = sanitize_cs_identifier(p["name"])
                    p_type = map_type_to_csharp(p["type_expr"], is_param=True)
                    param_strs.append(f"{p_type} {p_name}")

                sig_params = ", ".join(param_strs)
                lines.append(f"        public {static_mod}{ret_type} {m_name}({sig_params})")
                lines.append("        {")
                if ret_type == "void":
                    lines.append("            // Invoker trampoline")
                    lines.append("            return;")
                elif ret_type == "Task":
                    lines.append("            return Task.CompletedTask;")
                elif "Task<" in ret_type:
                    lines.append("            return Task.FromResult<object?>(null)!;")
                elif ret_type in ("int", "uint", "long", "ulong", "float", "double"):
                    lines.append("            return default;")
                elif ret_type == "bool":
                    lines.append("            return false;")
                else:
                    lines.append("            return default!;")
                lines.append("        }")
                lines.append("")

            lines.append("    }")
            lines.append("")

        lines.append("}")
        lines.append("")
        conn.close()
        return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="UTSS C# Binding Generator")
    parser.add_argument("--db", required=True, help="Path to input SQLite catalog database")
    parser.add_argument("--out", default="UtssPackages.g.cs", help="Output C# source file path")
    parser.add_argument("--namespace", default="Utss.Generated", help="Target C# namespace")
    args = parser.parse_args()

    db_path = Path(args.db)
    if not db_path.exists():
        print(f"Error: Database file does not exist: {db_path}", file=sys.stderr)
        sys.exit(1)

    bindgen = CSharpBindgen(db_path)
    code = bindgen.generate(target_namespace=args.namespace)

    out_path = Path(args.out)
    out_path.write_text(code, encoding="utf-8")
    print(f"[UTSS Bindgen] Emitted {len(code.splitlines())} lines of C# bindings to {out_path}")


if __name__ == "__main__":
    main()
